# Generate test/fixtures/predict_reference.jl, the frozen `predict` reference
# (KIM-68).
#
# The M4 freeze (spec §12 2026-10-30) requires any change to `predict` after it to
# reproduce the frozen code's results on the same seeds before any M5 job, shown old
# against new and threaded against serial. This runs the calls in
# test/fixtures/predict_reference_calls.jl, included from this script's own tree,
# each serial and threaded. It refuses if the two differ, and writes every result
# as plain values with `repr`, whose Float64s round-trip exactly. Parsing the
# written file back checks that. test/test_predict_reference.jl reruns the calls and
# compares.
#
# Run it against the tree to be recorded, from inside that tree:
#   cd <worktree> && julia --project=. --threads=4 <path to this script> <out>
# The header names that tree's commit (the code that ran) and this script's (the
# generator). dev/scripts/make_predict_reference.slurm runs it against one tree or
# more on one node and compares the bodies. Twice on one tree shows the output is
# deterministic. On the frozen tree and a later one it is the bitwise
# old-against-new check.

using InferCell
using Dates

include(joinpath(@__DIR__, "..", "..", "test", "fixtures", "predict_reference_calls.jl"))

const OUT = only(ARGS)
short(dir) = strip(read(`git -C $dir rev-parse --short HEAD`, String))
# The paths are from the tree's top (`:/`), since `git -C` reads them from `dir`, and
# for the generator that is dev/scripts.
dirty(dir, paths) = !isempty(strip(read(`git -C $dir status --porcelain -- $paths`, String)))
const CODE_PATHS = [":/src", ":/Project.toml", ":/Manifest.toml"]
const GEN_PATHS = [":/dev/scripts/make_predict_reference.jl",
                   ":/test/fixtures/predict_reference_calls.jl"]
const CODE, GEN = short(pwd()), short(@__DIR__)
Threads.nthreads() > 1 || @warn "one thread: the threaded calls run serially"

function main()
    results = Pair{Symbol, Any}[]
    for (name, run) in predict_reference_calls()
        t = @elapsed s = run(false)
        u = run(true)
        isequal(s, u) ||
            error("call $name: threaded differs from serial at $(_pref_diff(s, u; rtol = 0.0, atol = 0.0))")
        push!(results, name => s)
        println("$name: $(round(t; digits = 1)) s serial, threaded equal")
        flush(stdout)
    end
    body = IOBuffer()
    println(body, "const PREDICT_REFERENCE_COMMIT = \"$CODE\"")
    println(body, "const PREDICT_REFERENCE_POSTERIOR = ", repr(predict_reference_posterior()))
    println(body, "const PREDICT_REFERENCE = (;")
    for (name, r) in results
        println(body, "    $name = (;")
        for k in keys(r)
            println(body, "        $k = ", repr(r[k]), ",")
        end
        println(body, "    ),")
    end
    println(body, ")")
    text = String(take!(body))

    # Every value must read back as itself.
    m = Module()
    Base.include_string(m, text)
    back = Base.invokelatest(getfield, m, :PREDICT_REFERENCE)
    for (name, r) in results
        isequal(back[name], r) ||
            error("call $name does not round-trip: $(_pref_diff(back[name], r; rtol = 0.0, atol = 0.0))")
    end

    open(OUT, "w") do io
        println(io, "# The frozen `predict` reference (KIM-68): every result of the calls in")
        println(io, "# test/fixtures/predict_reference_calls.jl, serial (threaded gave the same).")
        println(io, "# Generated by dev/scripts/make_predict_reference.jl. Do not edit by hand.")
        println(io, "# Code: $CODE", dirty(pwd(), CODE_PATHS) ? " (WARNING: src/ or manifest dirty)" : "",
                "; generator: $GEN", dirty(@__DIR__, GEN_PATHS) ? " (dirty)" : "")
        println(io, "# Julia $(VERSION), $(Threads.nthreads()) threads, on $(gethostname()), job ",
                get(ENV, "SLURM_JOB_ID", "none"), ", $(Dates.now())")
        println(io, "# Floats are written by `repr`, which round-trips them exactly.")
        println(io)
        print(io, text)
    end
    println("wrote $OUT: code $CODE, generator $GEN")
end

main()
