p("## 11.7 — check 7's census on the charged-tRNA counter")
p()
p("One full cycle (6,300 handshakes, 1 s drain) per pool, charged fraction 0.8,")
p("`k_chg` re-derived per pool (D14). Translation carries only `tRNA_translat`,")
p("so the census counts that counter alone. \"Clipped\" is drains at which the")
p("counter carried a deficit; \"min charged\" is the charged pool's minimum over")
p("the cycle, in particles, at handshake resolution; \"buffer\" is the charged")
p("pool at cycle end over the cycle's mean residue flux.")
p()
p("| pool (mM) | clipped / drains | final deficit | min charged | steady charged fraction | residues/s | buffer (s) | wall (s) |")
p("|---|---|---|---|---|---|---|---|")
census_rows = []
for pool in POOLS
    ms = AbstractSubModel[NucleotideRecycling(), HeldGlycolytic(),
                          TrnaCharging(pool_mM = pool), birth_death()...,
                          CoreATranslation(counters = TRNA_ONLY)]
    d = build_problem(ms; tspan = (0.0, float(CYCLE)))
    iu, ic = idx(ms, :M_trna_c, :ode), idx(ms, :M_trna_chg_c, :ode)
    tl = ms[end]
    off = sum(length(states(m)) for m in ms if formalism(m) === :jump) - length(states(tl))
    u0 = d.jump.u[off .+ (1:length(states(tl)))]
    Random.seed!(1107)
    wall = @elapsed rec = run_handshake!(d, CYCLE)
    c = clipping_census(d)
    chg = [u[ic] for u in rec.ode]
    frac = [u[ic] / (u[iu] + u[ic]) for u in rec.ode]
    made = proteins_made(tl, u0, d.jump.u[off .+ (1:length(states(tl)))])
    flux = sum(made .* res) / CYCLE
    buffer = chg[end] * d.factor / flux
    push!(census_rows, (; pool, clipped = c.clipped, drains = c.drains, flux, buffer,
                        minchg = minimum(chg) * d.factor))
    p(@sprintf("| %.3f | %d / %d | %.1f | %.0f | %.4f | %.1f | %.2f | %.1f |",
               pool, c.clipped, c.drains, sum(c.deficits), minimum(chg) * d.factor,
               mean(frac[end-599:end]), flux, buffer, wall))
end
p()
clear = [r.pool for r in census_rows if r.clipped == 0]
p("Pools with zero clips over the cycle: ", isempty(clear) ? "none" :
  join((@sprintf("%.3f", x) for x in clear), ", "), " mM. ",
  "Check 1b's floor (task 9.8) needs at least 0.125 mM at 0.8 charged.")
