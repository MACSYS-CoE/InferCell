# Spec §11 tasks 11.7 and 11.10: whether translation's charged-tRNA counter
# can clip, the charged-pool elasticity of the translation constant, and the
# protein fold change over a cycle.
#
# 11.7. Check 7's census on the tRNA counter, over a full 6,300 s cycle, at
#       each of phase 9's pool sizes. It feeds task 9.8's scan, whose check 7
#       half was deferred here: 9.8 gave the analytic buffer, and this gives
#       the census with translation itself as the consumer. Composition:
#       NucleotideRecycling + HeldGlycolytic + TrnaCharging + live transcripts
#       (transcription and decay stripped of every counter and edge) +
#       CoreATranslation carrying only the tRNA counter, so the census counts
#       that counter and nothing else. The pool's k_chg is re-derived for each
#       pool, as D14 does.
#
# 11.10. The elasticity is analytic (`translation_elasticity`), checked against
#       a central difference through the module's own `rate_constants`. The
#       fold change is measured three ways: jump-only (transcription, decay
#       and translation at the nominal charged pool, eight seeds), in the full
#       seven-module hybrid (one seed, every counter), and analytically as
#       1 + k·m̄·T/P₀ at the measured transcript means. The hybrid run also
#       reports when each counter first clips and the wall-clock per cycle.
#
# Usage: julia --project dev/scripts/translation_diagnostics.jl
# Regenerate: sbatch dev/scripts/translation_diagnostics.slurm

