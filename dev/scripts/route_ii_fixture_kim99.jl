# KIM-99: freeze route (ii)'s mixed log-density on the reduced model before any speed-up,
# so test/test_corea_mixed.jl can hold every later commit to it within 1e-10.
#
# Usage: julia --project dev/scripts/route_ii_fixture_kim99.jl <fixture path>
# Run from a detached worktree at a pushed commit whose src/ is the code to freeze
# (fixture-provenance rule); the fixture names that commit.
#
# The setup is test/test_corea_mixed.jl's `corea_case(120.0)`: corea_dataset(17_200_001;
# ncells = 2, horizon = 120.0, targets = COREA_TARGETS), mixed_setup on d11_models(),
# default tolerances, δ = S = 0. x: the truth, the prior median, and two points jittered
# from the truth by 0.25 prior SD (Xoshiro(99)), inside the support box. Each x's
# log-density, and its ForwardDiff gradient, are written by `repr`, which round-trips.

include(joinpath(@__DIR__, "pilot_common.jl"))
using ForwardDiff
using Random

function main(path)
    ds = corea_dataset(17_200_001; ncells = 2, horizon = 120.0, targets = COREA_TARGETS)
    s = mixed_setup(ds; models = d11_models(), targets = COREA_TARGETS)
    truth = Dict(ds.truth.values)
    xt = vcat([log(truth[n]) for n in s.names], log(ds.sigma))
    rng = Xoshiro(99)
    sd = mixed_prior_sd(s)
    xs = [xt, mixed_prior_median(s), xt .+ 0.25 .* sd .* randn(rng, length(xt)),
          xt .+ 0.25 .* sd .* randn(rng, length(xt))]
    ℓ(z) = mixed_logdensity(s, z)
    vals = [ℓ(x) for x in xs]
    all(isfinite, vals) || error("a fixture x has a non-finite log-density: $vals")
    grads = [ForwardDiff.gradient(ℓ, x) for x in xs]
    say("log-densities: ", vals)
    open(path, "w") do io
        println(io, "# Route (ii)'s mixed log-density on the reduced model, frozen before KIM-99's")
        println(io, "# speed-up. Generated by dev/scripts/route_ii_fixture_kim99.jl. Do not edit by hand.")
        println(io, "# Code: ", COMMIT, " (", COMMIT_FULL, "); job ", JOB, "; on ", RAN_ON.host, " (",
                RAN_ON.cpu, "); Julia ", RAN_ON.julia, "; ", now())
        println(io, "# Setup: test/test_corea_mixed.jl's corea_case(120.0), default tolerances, δ = S = 0.")
        println(io, "# Floats are written by `repr`, which round-trips them exactly.\n")
        println(io, "const ROUTE_II_DENSITY_COMMIT = ", repr(String(COMMIT)))
        println(io, "const ROUTE_II_DENSITY_NAMES = ", repr(mixed_parameter_names(s)))
        println(io, "const ROUTE_II_DENSITY_X = ", repr(xs))
        println(io, "const ROUTE_II_DENSITY = ", repr(vals))
        println(io, "const ROUTE_II_DENSITY_GRAD = ", repr(grads))
    end
    print(read(path, String))
end

main(only(ARGS))
