MACROS = []  # (key, latex, source)


# ---------------------------------------------------------------- formatting

def n(x):
    """An integer count with LaTeX thousands separators."""
    return "{:,}".format(int(round(x))).replace(",", "{,}")


def f(x, d):
    """x to d decimals, rounded to nearest."""
    return "%.*f" % (d, x)


def ceil_to(x, d):
    """x rounded UP to d decimals: for an upper bound that must still hold."""
    return "%.*f" % (d, math.ceil(x * 10 ** d - 1e-9) / 10 ** d)


def sci(x, sig=2):
    """x in scientific notation as LaTeX, usable in text and maths."""
    if x == 0:
        return "0"
    e = int(math.floor(math.log10(abs(x))))
    m = x / 10 ** e
    if round(m, sig - 1) >= 10:
        m, e = m / 10, e + 1
    return r"\ensuremath{%s \times 10^{%d}}" % (f(m, sig - 1), e)


# ---------------------------------------------------------------- reading results

def rel(path):
    return os.path.relpath(path, ROOT)


def rows(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def load_json(path):
    with open(path) as fh:
        return json.load(fh)


def put(key, value, source):
    if not re.fullmatch(r"[A-Za-z0-9._]+", key):
        raise ValueError("key %r: use letters, digits and dots only" % key)
    if any(k == key for k, _, _ in MACROS):
        raise KeyError("duplicate key " + key)
    MACROS.append((key, value, source))


