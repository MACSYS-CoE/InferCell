def quoted_keys():
    """The \\pn keys paper/main.tex quotes, following \\input/\\include."""
    seen, keys = set(), set()

    def scan(path):
        if path in seen or not os.path.isfile(path):
            return
        seen.add(path)
        with open(path, encoding="utf-8") as fh:
            tex = re.sub(r"(?<!\\)%.*", "", fh.read())
        keys.update(re.findall(r"\\pn\{([^}]+)\}", tex))
        for name in re.findall(r"\\(?:input|include)\{([^}]+)\}", tex):
            p = os.path.join(PAPER, name)
            scan(p if p.endswith(".tex") else p + ".tex")

    scan(os.path.join(PAPER, "main.tex"))
    return keys


def render(macros):
    return HEADER + "".join("\\pndef{%s}{%s}%% %s\n" % m for m in macros)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--all", action="store_true")
    a = ap.parse_args()
    compute()
    wanted = None if a.all else quoted_keys()
    macros = [m for m in MACROS if wanted is None or m[0] in wanted]
    elsewhere = set()
    missing = sorted((wanted or set()) - {k for k, _, _ in MACROS} - elsewhere)
    with open(a.out, "w") as fh:
        fh.write(render(macros))
    if a.list:
        for k, v, s in MACROS:
            print("%-32s = %-20s (%s)" % (k, v, s))
    if missing:
        print("quoted but not computed: " + ", ".join(missing))
    print("%d of %d numbers written to %s" % (len(macros), len(MACROS), rel(a.out)))


if __name__ == "__main__":
    main()
