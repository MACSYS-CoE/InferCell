"""Every number the paper quotes, as LaTeX macros (from the /write-paper skill's template).

Most results live in Slurm archives outside the repo, so each put() is a literal
transcribed from a result note, and its source names the note and the job id.

    python3 scripts/paper_numbers.py            # writes paper/numbers.tex
    python3 scripts/paper_numbers.py --list     # also prints every key = value  (source)
    python3 scripts/paper_numbers.py --all      # write every number, not only those the paper quotes
    python3 scripts/paper_numbers.py --out X    # write to X instead (check_paper.py uses this)

The paper quotes a result only through \\pn{key}. This script is the one place that turns
result files into those strings, and each macro carries its source path as a comment.
Only the keys that paper/main.tex (with its \\input files) quotes are written, unless --all.
The output has no timestamp, so a rerun on the same results is byte-identical, which is
what check_paper.py tests. An undefined key stops the LaTeX build.

To use: copy to scripts/paper_numbers.py, then fill in compute() with one put() per number.
Rounding is to nearest at the precision the text needs; a bound ("at most x") rounds up so
the bound still holds. Counts get LaTeX thousands separators ("9{,}998").
Standard library only (add numpy etc. if the project already depends on them).
"""
