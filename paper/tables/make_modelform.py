#!/usr/bin/env python3
"""Counts for the model-form table, and the full list of reductions for S1 File.

Reads paper/tables/reductions_raw.tsv, the output of reductions_dump.jl (Slurm job
20165612, on package source identical to main at 3c677a1). Writes:
- modelform_counts.tex: a \\pndef per category and composition;
- S1_File_reductions.tsv: every declaration, with the reduced model's public name.

Run from the repository root: python3 paper/tables/make_modelform.py
"""
import collections
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
WORDS = {"reduced": "red", "m0": "mz"}

with open(os.path.join(HERE, "reductions_raw.tsv"), newline="") as f:
    rows = list(csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE))

counts = collections.Counter((r["composition"], r["category"]) for r in rows)
total = collections.Counter(r["composition"] for r in rows if r["category"] != "driver_policy")

with open(os.path.join(HERE, "modelform_counts.tex"), "w") as f:
    f.write("%% Generated by make_modelform.py from reductions_raw.tsv. Do not edit.\n")
    for (comp, cat), n in sorted(counts.items()):
        f.write(f"\\pndef{{{WORDS[comp]}.{cat}}}{{{n}}}\n")
    for comp, n in sorted(total.items()):
        f.write(f"\\pndef{{{WORDS[comp]}.total}}{{{n}}}\n")

with open(os.path.join(HERE, "S1_File_reductions.tsv"), "w", newline="") as f:
    w = csv.writer(f, delimiter="\t", quoting=csv.QUOTE_NONE, escapechar="\\", lineterminator="\n")
    w.writerow(["composition", "category", "subject", "description"])
    for r in rows:
        w.writerow([r["composition"], r["category"], r["subject"],
                    r["description"].replace("Core A′", "the reduced model")])
